def _load_name_pool(filename: str, fallback: list[str]) -> list[str]:
    """Load editable name pools from data CSVs, falling back to built-ins."""
    path = Path(__file__).resolve().parent / "data" / filename
    names: list[str] = []
    seen: set[str] = set()

    if path.exists():
        try:
            with path.open("r", encoding="utf-8-sig", newline="") as file:
                reader = csv.DictReader(file)
                for row in reader:
                    name = str(row.get("name", "")).strip()
                    key = name.casefold()
                    if name and key not in seen:
                        names.append(name)
                        seen.add(key)
        except OSError:
            names = []
            seen.clear()

    if not names:
        for name in fallback:
            cleaned = str(name).strip()
            key = cleaned.casefold()
            if cleaned and key not in seen:
                names.append(cleaned)
                seen.add(key)

    return names


FIRST_NAME_POOL = _load_name_pool("first_names.csv", FIRST_NAMES)
LAST_NAME_POOL = _load_name_pool("last_names.csv", LAST_NAMES)


def generate_drivers(num_drivers: int, exclude_name: str = "Player") -> list[dict[str, object]]:
    """Generate AI driver dicts with names, skills and empty season stats."""
    drivers = []
    used_names = {exclude_name}

    while len(drivers) < num_drivers:
        full_name = f"{random.choice(FIRST_NAME_POOL)} {random.choice(LAST_NAME_POOL)}"
        if full_name in used_names:
            continue

        used_names.add(full_name)
        drivers.append(
            {
                "name": full_name,
                "nationality": random.choice(NATIONALITIES),
                "skill": random.randint(40, 95),
                "points": 0,
                "wins": 0,
            }
        )

    return drivers


